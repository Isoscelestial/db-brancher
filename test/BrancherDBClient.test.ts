import { randomUUID } from 'node:crypto';
import BrancherDBClient from '@/BrancherDBClient';
import { neonBranchProvider } from './providers/Neon.test';
import { UserRef } from '@/refs/UserRef';
import { Branch } from '@neon/sdk';

describe('BrancherDBClient using Neon', () => {
  const brancher = new BrancherDBClient(neonBranchProvider);

  const username = `vitest-${randomUUID()}`;
  const u: UserRef = { name: username };

  test('Fetch branches', async () => {
    const branches = await brancher.branch.getAll();
    expectTypeOf(branches).toExtend<Branch[]>();
  });

  let createdBranch: Branch;

  test('Create branch', async () => {
    createdBranch = await brancher.user.createBranch(u, {
      note: 'AUTO-GENERATED BY VITEST',
    });
    expectTypeOf(createdBranch).toExtend<Branch>();
  });

  test('Create branch 2', async () => {
    createdBranch = await brancher.user.createBranch(u, {
      note: 'AUTO-GENERATED BY VITEST',
    });
    expectTypeOf(createdBranch).toExtend<Branch>();
  });

  let childBranch: Branch;

  test('Create child branch on 2', async () => {
    childBranch = await brancher.user.createBranch(u, {
      note: 'AUTO-GENERATED BY VITEST',
      parentSlot: 2,
    });
    expectTypeOf(childBranch).toExtend<Branch>();
  });

  test('Validate child branch on 2', async () => {
    const parentSlot = await brancher.$util.getParentSlot(u, [2, 1]);
    expect(parentSlot).toEqual([2]);

    const parentBranch = await brancher.$util.getParentBranch(u, [2, 1]);
    expectTypeOf(parentBranch).toExtend<Branch | undefined>();
    expect(parentBranch?.id).toEqual(createdBranch.id);

    const childSlots = await brancher.$util.getChildSlots(u, [2]);
    expect(childSlots).toEqual([1]);
  });

  test('Reset child branch from parent', async () => {
    // TODO: Make change in parent branch
    // TODO: Make new branch
    const result = await brancher.user.resetBranchFromParent(u, [2, 1]);
    // TODO: Check if new branch has aforementioned change
    expectTypeOf(result).toExtend<Branch | void>();
  });

  test('Delete child branch', async () => {
    await brancher.user.deleteBranch(u, [2, 1]);

    const userBranches = await brancher.user.getBranches(u);

    expect(userBranches).toHaveLength(2);
  });

  test('Validate no more parent/child relationship on 2', async () => {
    const childSlots = await brancher.$util.getChildSlots(u, [2]);
    expect(childSlots).toEqual(undefined);
  });

  test('List branches', async () => {
    const userBranches = await brancher.user.getBranches(u);

    expect(userBranches).toHaveLength(2);
    expect(userBranches[0].id).toBe(createdBranch.id);
    expectTypeOf(userBranches[0]).toExtend<Branch>();
  });

  test('Get connection URL', async () => {
    const uri = await brancher.user.getConnectionURL(u, 1);
    expect(uri).toMatch(
      /^postgres(?:ql)?:\/\/(?:[^:@]+(?::[^@]*)?@)?[^:/?#]+(?::\d+)?\/[^?#]+(?:\?.*)?$/,
    );
  });

  test('Delete branches', async () => {
    await brancher.user.deleteBranch(u, 1);
    await brancher.user.deleteBranch(u, 2);

    const userBranches = await brancher.user.getBranches(u);

    expect(userBranches).toHaveLength(0);
  });
});

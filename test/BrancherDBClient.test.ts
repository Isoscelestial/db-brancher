import { randomBytes } from 'node:crypto';
import BrancherDBClient from '@/BrancherDBClient';
import { neonBranchProvider } from './providers/Neon.test';
import { UserRef } from '@/refs/UserRef';
import { Branch } from '@neon/sdk';

describe('BrancherDBClient using Neon', () => {
  const brancher = new BrancherDBClient(neonBranchProvider);

  const username = `vitest-${randomBytes(8).toString('hex')}`;
  const u: UserRef = { githubUsername: username };

  test('Fetch branches', async () => {
    const branches = await brancher.branch.getAll();
    expectTypeOf(branches).toExtend<Branch[]>();
  });

  let createdBranch: Branch;

  test('Create branch', async () => {
    createdBranch = await brancher.user.createBranch(
      u,
      'AUTO-GENERATED BY VITEST',
    );
    expectTypeOf(createdBranch).toExtend<Branch>();
  });

  test('List branches', async () => {
    const userBranches = await brancher.user.getBranches(u);

    expect(userBranches).toHaveLength(1);
    expect(userBranches[0].id).toBe(createdBranch.id);
    expectTypeOf(userBranches[0]).toExtend<Branch>();
  });

  test('Get connection URL', async () => {
    const uri = await brancher.user.getConnectionURL(u, 1);
    expect(uri).toMatch(
      /^postgres(?:ql)?:\/\/(?:[^:@]+(?::[^@]*)?@)?[^:/?#]+(?::\d+)?\/[^?#]+(?:\?.*)?$/,
    );
  });

  test('Delete branch', async () => {
    await brancher.user.deleteBranch(u, 1);

    const userBranches = await brancher.user.getBranches(u);

    expect(userBranches).toHaveLength(0);
  });
});
